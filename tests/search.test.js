const assert=require('node:assert/strict');
const S=require('../static/search.js');
const sample=(name,extra={})=>({id:1,name,sku:'',supplier:'Test',...extra});
const metal=sample('Bor 5,00mm HSS-Cobalt 1 stk pk');
for(const query of ['5mm bor','5 mm bor','5,0 mm stálbor','stalbor 5.00 mm','5mm járnbor','bor stál 5mm'])assert(S.matches(metal,query),query);
assert(S.matches(sample('BOR STÁL HSS 5MM TURBO MAX JORAN'),'5mm stálbor'));
assert(S.matches(sample('Bor 5x86mm HSS Stál'),'5mm stálbor'));
assert(S.matches(sample('Trébor 5mm'),'5mm bor'));
assert(!S.matches(sample('Trébor 5mm'),'5mm stálbor'));
assert(!S.matches(sample('Trébor HSS 5mm'),'5mm stálbor'));
for(const name of ['Bor 5,5mm HSS','Bor 15mm HSS','Bor 50mm HSS','Borvél 5,0Ah','Borskrúfa 5mm','Bor fyrir gatsagir 105mm'])assert(!S.matches(sample(name),'5mm bor'),name);
assert(!S.matches(sample('Borasett HSS 1-10mm'),'5mm bor'));
assert(S.matches(sample('Kúluloki ryðfrítt',{sku:'E1020103'}),'kululoki rydfritt'));
assert(S.matches(sample('Anything',{sku:'00123'}),'00123'));
assert(S.comparable(metal,sample('Stálbor 5mm HSS-G',{id:2})));
assert(!S.comparable(metal,sample('Trébor 5mm',{id:2})));
assert(!S.comparable(metal,sample('Bor 5,5mm HSS',{id:2})));
const publicData=require('../seeds/public-market.json').products;
assert.equal(publicData.filter(o=>S.matches(o,'5mm bor')).length,6);
assert.equal(publicData.filter(o=>S.matches(o,'5mm stálbor')).length,5);
assert.equal(publicData.filter(o=>S.matches(o,'5mm trébor')).length,1);
console.log('Search checks passed: aliases, decimal variants, diameters, materials, sets, public records');
